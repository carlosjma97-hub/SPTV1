"""Contrato que debe cumplir cualquier backend (Windows real o simulado)."""
from __future__ import annotations

from abc import ABC, abstractmethod
from typing import Optional

from .models import Job, PrinterInfo


class BackendError(Exception):
    """Fallo de una operacion del sistema de impresion."""


class PrinterNotFound(BackendError):
    pass


class Backend(ABC):
    # ---- lectura ----
    @abstractmethod
    def list_printers(self) -> list[PrinterInfo]: ...
    @abstractmethod
    def get_printer(self, name: str) -> PrinterInfo: ...
    @abstractmethod
    def get_ticket(self, name: str) -> Optional[str]: ...
    @abstractmethod
    def duplex_caps(self, name: str) -> Optional[list[str]]: ...
    @abstractmethod
    def list_jobs(self, name: str) -> list[Job]: ...
    @abstractmethod
    def printers_on_port(self, port_name: str) -> list[str]: ...
    @abstractmethod
    def port_exists(self, port_name: str) -> bool: ...
    @abstractmethod
    def spooler_running(self) -> bool: ...
    @abstractmethod
    def check_host(self, host: str, port: int) -> tuple[bool, bool]: ...   # (ping, tcp)
    @abstractmethod
    def default_printer(self) -> str: ...
    @abstractmethod
    def file_owner(self, path: str) -> str: ...

    # ---- escritura (requieren administrador en Windows) ----
    @abstractmethod
    def remove_job(self, name: str, job_id: int) -> None: ...
    @abstractmethod
    def restart_spooler(self) -> None: ...
    @abstractmethod
    def remove_printer(self, name: str) -> None: ...
    @abstractmethod
    def rename_printer(self, old_name: str, new_name: str) -> None: ...
    @abstractmethod
    def remove_port(self, port_name: str) -> None: ...
    @abstractmethod
    def add_port(self, p: PrinterInfo) -> None: ...
    @abstractmethod
    def add_printer(self, p: PrinterInfo) -> None: ...
    @abstractmethod
    def set_ticket(self, name: str, xml: str) -> None: ...
    @abstractmethod
    def set_duplex(self, name: str, mode: str) -> None: ...

    # ---- contexto de usuario ----
    @abstractmethod
    def set_default_printer(self, name: str) -> None: ...
    @abstractmethod
    def print_test_page(self, name: str) -> None: ...
